/**
 * Register a receipt print before the browser prints it. The first print is
 * normal; every later print is a reprint and is written to the audit log.
 */
export async function printReceiptAction(
  _previous: PaymentActionState | undefined,
  formData: FormData,
): Promise<PaymentActionState> {
  const parsed = receiptPrintSchema.safeParse({
    businessId: field(formData, "businessId"),
    receiptId: field(formData, "receiptId"),
  });
  if (!parsed.success) return { error: "Invalid request." };
  const { businessId, receiptId } = parsed.data;

  const scope = await scopeOf("receipts", receiptId, businessId);
  if (!scope) return { error: "Receipt not found in this business." };

  const auth = await authorise(businessId, "billing.manage", scope.outletId);
  if ("error" in auth) return { error: auth.error };

  try {
    const printCount = await recordReceiptPrintRpc({ actorUserId: auth.userId, receiptId });
    return { ok: true, printCount: Number(printCount) };
  } catch (error) {
    return ledgerFailure(error);
  }
}

/** Create or update a payment method for the business. Requires billing.manage. */
export async function savePaymentMethodAction(
  _previous: PaymentActionState | undefined,
  formData: FormData,
): Promise<PaymentActionState> {
  const parsed = paymentMethodSchema.safeParse({
    businessId: field(formData, "businessId"),
    methodId: field(formData, "methodId"),
    key: field(formData, "key"),
    label: String(formData.get("label") ?? ""),
    kind: field(formData, "kind"),
    requiresReference: field(formData, "requiresReference") || "false",
    isActive: field(formData, "isActive") || "true",
  });
  if (!parsed.success) {
    return { error: "Please check the payment method.", fieldErrors: zodFieldErrors(parsed.error) };
  }
  const data = parsed.data;
  if (!data.methodId && !METHOD_KEY_PATTERN.test(data.key)) {
    return { error: "Method key: lowercase letters, digits and underscores, starting with a letter.", fieldErrors: { key: ["Invalid key."] } };
  }

  const auth = await authorise(data.businessId, "billing.manage", null);
  if ("error" in auth) return { error: auth.error };

  try {
    await savePaymentMethodRpc({
      actorUserId: auth.userId,
      businessId: data.businessId,
      methodId: data.methodId || null,
      key: data.methodId ? null : data.key,
      label: data.label,
      kind: data.kind,
      requiresReference: data.requiresReference,
      isActive: data.isActive,
    });
    return { ok: true };
  } catch (error) {
    return ledgerFailure(error);
  }
}
