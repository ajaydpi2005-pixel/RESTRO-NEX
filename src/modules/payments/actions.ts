/**
 * Phase 10 — billing server actions.
 *
 * Security model (same as Phases 8–9):
 *  - the actor is the session user, never a form field;
 *  - every row id is resolved server-side and must belong to the business
 *    named in the form; the OUTLET comes from that row, not from the client;
 *  - requirePermission checks the role AND the outlet grant before any RPC;
 *  - amounts arrive as display strings and become integer minor units here;
 *  - the RPCs repeat the permission + membership checks in SQL and own every
 *    money write, the batch/refund idempotency keys and the audit trail.
 */

export interface PaymentActionState {
  ok?: boolean;
  error?: string;
  fieldErrors?: Partial<Record<string, string[]>>;
  duplicate?: boolean;
  receiptId?: string;
  receiptNo?: string;
  invoiceId?: string;
  invoiceNo?: string;
  printCount?: number;
}

const GENERIC_ERROR = "Something went wrong. Please try again.";
const SIGN_IN_AGAIN = "Please sign in again.";

function zodFieldErrors(error: ZodError): Partial<Record<string, string[]>> {
  const fieldErrors: Partial<Record<string, string[]>> = {};
  for (const issue of error.issues) {
    const key = issue.path.join(".") || "form";
    (fieldErrors[key] ??= []).push(issue.message);
  }
  return fieldErrors;
}

function field(formData: FormData, name: string): string {
  return String(formData.get(name) ?? "").trim();
}

type Authorised = { userId: string } | { error: string };

async function authorise(businessId: string, permission: Permission, outletId: string | null): Promise<Authorised> {
  const userId = await getSessionUserId();
  if (!userId) return { error: SIGN_IN_AGAIN };
  try {
    await requirePermission({ businessId, permission, outletId: outletId ?? undefined });
  } catch (error) {
    return { error: permissionErrorMessage(error) };
  }
  return { userId };
}

function ledgerFailure(error: unknown): PaymentActionState {
  if (error instanceof LedgerError) return { error: error.message };
  return { error: GENERIC_ERROR };
}

/** Resolve a row's outlet and prove it belongs to the business named in the form. */
async function scopeOf(
  table: "orders" | "payments" | "invoices" | "receipts",
  id: string,
  businessId: string,
): Promise<{ outletId: string } | null> {
  const admin = createAdminClient();
  const { data } = await admin.from(table).select("id, business_id, outlet_id").eq("id", id).maybeSingle();
  if (!data || data.business_id !== businessId) return null;
  return { outletId: String(data.outlet_id) };
}

/**
 * Record one or more payment lines against an order (split / partial /
 * multi-method). Form fields: businessId, orderId, batchKey, lines (JSON).
 * The batchKey is generated by the client per payment attempt; a retry with
 * the same key returns the original receipt instead of charging again.
 */
export async function recordPaymentsAction(
  _previous: PaymentActionState | undefined,
  formData: FormData,
): Promise<PaymentActionState> {
  const parsed = recordPaymentsSchema.safeParse({
    businessId: field(formData, "businessId"),
    orderId: field(formData, "orderId"),
    batchKey: field(formData, "batchKey"),
    lines: String(formData.get("lines") ?? ""),
  });
  if (!parsed.success) {
    return { error: "Please check the payment details.", fieldErrors: zodFieldErrors(parsed.error) };
  }
  const { businessId, orderId, batchKey, lines } = parsed.data;

  const scope = await scopeOf("orders", orderId, businessId);
  if (!scope) return { error: "Order not found in this business." };

  const auth = await authorise(businessId, "billing.manage", scope.outletId);
  if ("error" in auth) return { error: auth.error };

  const ledgerLines: { methodKey: string; amountMinor: number; tenderedMinor: number | null; reference: string | null }[] = [];
  for (const line of lines) {
    const amountMinor = parseMoneyToMinor(line.amount);
    if (amountMinor === null || amountMinor <= 0) {
      return { error: "Each payment needs an exact amount greater than zero." };
    }
    let tenderedMinor: number | null = null;
    if (line.tendered) {
      tenderedMinor = parseMoneyToMinor(line.tendered);
      if (tenderedMinor === null) return { error: "Cash tendered must be an exact amount." };
    }
    ledgerLines.push({
      methodKey: line.methodKey,
      amountMinor,
      tenderedMinor,
      reference: line.reference ? line.reference : null,
    });
  }

  try {
    const result = await recordPaymentBatch({
      actorUserId: auth.userId,
      orderId,
      batchKey,
      lines: ledgerLines,
    });
    return { ok: true, duplicate: result.duplicate, receiptId: result.receiptId, receiptNo: result.receiptNo };
  } catch (error) {
    return ledgerFailure(error);
  }
}

/** Refund part or all of one captured payment. Requires refunds.process. */
export async function refundPaymentAction(
  _previous: PaymentActionState | undefined,
  formData: FormData,
): Promise<PaymentActionState> {
  const parsed = refundSchema.safeParse({
    businessId: field(formData, "businessId"),
    paymentId: field(formData, "paymentId"),
    amount: field(formData, "amount"),
    reason: String(formData.get("reason") ?? ""),
    refundKey: field(formData, "refundKey"),
  });
  if (!parsed.success) {
    return { error: "Please check the refund details.", fieldErrors: zodFieldErrors(parsed.error) };
  }
  const { businessId, paymentId, amount, reason, refundKey } = parsed.data;

  const scope = await scopeOf("payments", paymentId, businessId);
  if (!scope) return { error: "Payment not found in this business." };

  const auth = await authorise(businessId, "refunds.process", scope.outletId);
  if ("error" in auth) return { error: auth.error };

  const amountMinor = parseMoneyToMinor(amount);
  if (amountMinor === null || amountMinor <= 0) return { error: "Enter an exact refund amount greater than zero." };

  try {
    const result = await refundPaymentRpc({
      actorUserId: auth.userId,
      paymentId,
      amountMinor,
      reason,
      clientRef: refundKey,
    });
    return { ok: true, duplicate: result.duplicate, receiptId: result.receipt_id, receiptNo: result.receipt_no };
  } catch (error) {
    return ledgerFailure(error);
  }
}

/** Issue the numbered invoice for an order (one issued invoice per order). */
export async function issueInvoiceAction(
  _previous: PaymentActionState | undefined,
  formData: FormData,
): Promise<PaymentActionState> {
  const parsed = issueInvoiceSchema.safeParse({
    businessId: field(formData, "businessId"),
    orderId: field(formData, "orderId"),
  });
  if (!parsed.success) return { error: "Invalid request." };
  const { businessId, orderId } = parsed.data;

  const scope = await scopeOf("orders", orderId, businessId);
  if (!scope) return { error: "Order not found in this business." };

  const auth = await authorise(businessId, "billing.manage", scope.outletId);
  if ("error" in auth) return { error: auth.error };

  try {
    const result = await issueInvoiceRpc({ actorUserId: auth.userId, orderId });
    return { ok: true, duplicate: result.duplicate, invoiceId: result.invoice_id, invoiceNo: result.invoice_no };
  } catch (error) {
    return ledgerFailure(error);
  }
}

