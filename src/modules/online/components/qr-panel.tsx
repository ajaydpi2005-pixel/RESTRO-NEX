"use client";

import { useRouter } from "next/navigation";
import { useState, useTransition } from "react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { issueQrCodeAction, revokeQrCodeAction } from "../actions";
import type { QrCodeRow } from "../types";

/**
 * Phase 17 — QR table codes. A code's link is shown once, at issue. The database
 * keeps only a hash of it, so a lost link has to be replaced by issuing a new code.
 */

interface Issued {
  url: string;
  svg: string;
  label: string;
  tableLabel: string;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

export function QrPanel(props: {
  businessId: string;
  outletId: string;
  tables: { id: string; label: string }[];
  codes: QrCodeRow[];
  canManage: boolean;
  restaurantName: string;
}) {
  const router = useRouter();
  const [tableId, setTableId] = useState(props.tables[0]?.id ?? "");
  const [label, setLabel] = useState("");
  const [issued, setIssued] = useState<Issued | null>(null);
  const [message, setMessage] = useState<string | null>(null);
  const [pending, startTransition] = useTransition();

  function issue() {
    setMessage(null);
    if (!tableId) {
      setMessage("Choose a table first.");
      return;
    }
    startTransition(async () => {
      const result = await issueQrCodeAction({
        businessId: props.businessId,
        outletId: props.outletId,
        tableId,
        label: label.trim() || undefined,
      });
      if (!result.ok) {
        setMessage(result.error);
        return;
      }
      setIssued({
        url: result.url,
        svg: result.svg,
        label: result.label,
        tableLabel: result.tableLabel,
      });
      setLabel("");
      router.refresh();
    });
  }

  function revoke(qrId: string) {
    setMessage(null);
    startTransition(async () => {
      const result = await revokeQrCodeAction({
        businessId: props.businessId,
        outletId: props.outletId,
        qrId,
      });
      if (!result.ok) {
        setMessage(result.error);
        return;
      }
      router.refresh();
    });
  }

  function printIssued() {
    if (!issued) return;
    const win = window.open("", "_blank", "noopener,noreferrer,width=480,height=640");
    if (!win) {
      setMessage("Your browser blocked the print window. Allow pop-ups and try again.");
      return;
    }
    // The SVG was generated by the server from the code's URL. The restaurant name and
    // label are staff-typed text, so they are escaped before they reach the page.
    win.document.write(`<!doctype html><html><head><title>QR ${escapeHtml(issued.label)}</title>
<style>body{font-family:system-ui,sans-serif;text-align:center;padding:32px}svg{width:260px;height:260px}p{margin:6px 0}</style>
</head><body><p><strong>${escapeHtml(props.restaurantName)}</strong></p><p>${escapeHtml(issued.tableLabel)}</p>
<div>${issued.svg}</div><p>Scan to order from your table</p></body></html>`);
    win.document.close();
    win.focus();
    win.print();
  }

  async function copyLink() {
    if (!issued) return;
    try {
      await navigator.clipboard.writeText(issued.url);
      setMessage("Link copied.");
    } catch {
      setMessage("Could not copy. Select the link and copy it by hand.");
    }
  }

  return (
    <Card>
      <CardHeader>
        <CardTitle className="text-base">Table QR codes</CardTitle>
        <CardDescription>
          Each code opens the menu for one table. Revoke a code if it is lost or moved. Staff
          confirm each table order.
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-6">
        {props.canManage ? (
          <div className="grid gap-3 sm:grid-cols-[1fr_1fr_auto] sm:items-end">
            <div className="space-y-1">
              <Label htmlFor="qr-table">Table</Label>
              <select
                id="qr-table"
                value={tableId}
                onChange={(e) => setTableId(e.target.value)}
                className="border-input bg-background h-9 w-full rounded-md border px-3 text-sm"
                disabled={pending || props.tables.length === 0}
              >
                {props.tables.length === 0 ? <option value="">No active tables</option> : null}
                {props.tables.map((t) => (
                  <option key={t.id} value={t.id}>
                    {t.label}
                  </option>
                ))}
              </select>
            </div>
            <div className="space-y-1">
              <Label htmlFor="qr-label">Label (optional)</Label>
              <Input
                id="qr-label"
                value={label}
                maxLength={60}
                onChange={(e) => setLabel(e.target.value)}
                placeholder="Defaults to the table name"
              />
            </div>
            <Button type="button" onClick={issue} disabled={pending || !tableId}>
              {pending ? "Working…" : "Create QR code"}
            </Button>
          </div>
        ) : (
          <p className="text-muted-foreground text-sm">
            Only owners and managers can create or revoke QR codes.
          </p>
        )}

        {issued ? (
          <div
            role="status"
            className="border-gold/50 bg-gold/5 grid gap-4 rounded-xl border p-4 sm:grid-cols-[auto_1fr]"
          >
            <div
              className="mx-auto w-44"
              aria-label={`QR code for ${issued.tableLabel}`}
              dangerouslySetInnerHTML={{ __html: issued.svg }}
            />
            <div className="space-y-3">
              <p className="font-medium">{issued.label} is ready.</p>
              <p className="text-muted-foreground text-sm">
                This link is shown only once. Print the code now. If you lose the link, revoke this
                code and create a new one.
              </p>
              <p className="bg-muted rounded-md px-3 py-2 font-mono text-xs break-all">
                {issued.url}
              </p>
              <div className="flex flex-wrap gap-2">
                <Button type="button" size="sm" onClick={printIssued}>
                  Print
                </Button>
                <Button type="button" size="sm" variant="outline" onClick={copyLink}>
                  Copy link
                </Button>
                <Button type="button" size="sm" variant="ghost" onClick={() => setIssued(null)}>
                  Done
                </Button>
              </div>
            </div>
          </div>
        ) : null}

        {message ? (
          <p role="status" className="text-muted-foreground text-sm">
            {message}
          </p>
        ) : null}

        <div className="overflow-x-auto">
          <table className="w-full text-sm">
            <thead>
              <tr className="border-border text-muted-foreground border-b text-left">
                <th className="py-2 pr-3 font-medium">Label</th>
                <th className="py-2 pr-3 font-medium">Table</th>
                <th className="py-2 pr-3 font-medium">Code</th>
                <th className="py-2 pr-3 font-medium">Status</th>
                <th className="py-2 font-medium">
                  <span className="sr-only">Actions</span>
                </th>
              </tr>
            </thead>
            <tbody>
              {props.codes.length === 0 ? (
                <tr>
                  <td colSpan={5} className="text-muted-foreground py-4">
                    No QR codes yet.
                  </td>
                </tr>
              ) : null}
              {props.codes.map((code) => (
                <tr key={code.id} className="border-border/60 border-b">
                  <td className="py-2 pr-3">{code.label}</td>
                  <td className="py-2 pr-3">{code.table_label ?? "—"}</td>
                  <td className="text-muted-foreground py-2 pr-3 font-mono text-xs">
                    {code.token_prefix}…
                  </td>
                  <td className="py-2 pr-3">
                    <Badge
                      variant="outline"
                      className={
                        code.status === "active" ? "border-green-600/50" : "border-destructive/50"
                      }
                    >
                      {code.status === "active" ? "Active" : "Revoked"}
                    </Badge>
                  </td>
                  <td className="py-2 text-right">
                    {props.canManage && code.status === "active" ? (
                      <Button
                        type="button"
                        variant="ghost"
                        size="sm"
                        disabled={pending}
                        onClick={() => revoke(code.id)}
                      >
                        Revoke
                      </Button>
                    ) : null}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </CardContent>
    </Card>
  );
}
